  const updated=await store.save(owner,customer.id,id,photoInput);
  assert.ok(updated.photo);assert.equal((await store.photo(owner,customer.id,id)).length>0,true);
  assert.deepEqual(await store.save(owner,customer.id,id,photoInput),updated);
  assert.equal((await store.list(admin,customer.id)).items.length,2);
  const match=await store.search(admin,'妞');assert.equal(match.items[0].customer.name,customer.name);assert.equal(match.items[0].pet.id,id);
